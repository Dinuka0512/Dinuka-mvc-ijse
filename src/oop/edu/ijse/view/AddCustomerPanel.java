    public void searchCustomer() throws Exception{
        String customerId = (String) Table.getValueAt(Table.getSelectedRow(),0);
        try {
            CustomerDto dto = customerControler.searchCustomer(customerId);
            if(dto != null){
                txtId.setText(dto.getId());
                txtTitle.setText(dto.getTitle());
                txtName.setText(dto.getName());
                txtDob.setText(dto.getDob());
                txtSalary.setText(Double.toString(dto.getSalary()));
                txtAddress.setText(dto.getAddress());
                txtCity.setText(dto.getCity());
                txtProvince.setText(dto.getProvince());
                txtPostalCode.setText(dto.getPostalCode());
            } else {
                JOptionPane.showMessageDialog(this, "Customer Not Found");
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }
    
    private void loadTable() {
        String columns[] = {"Customer Id", "Cutomer Name", "DOB", "Salary", "Address", "Province", "Postal Code"};
        DefaultTableModel dtm = new DefaultTableModel(columns, 0);
        Table.setModel(dtm);
        try {
            List<CustomerDto> customerDtos = customerControler.getAllCustomer();
            for (CustomerDto dto : customerDtos) {
                Object [] rowData = {dto.getId(), dto.getTitle() + " " + dto.getName(), dto.getDob(), dto.getSalary(), dto.getAddress() + ", " + dto.getCity(), dto.getProvince(), dto.getPostalCode()};
                dtm.addRow(rowData);
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
        
    }
    
    public void save(){
        try{
            CustomerDto customerDto = new CustomerDto(txtId.getText(),txtTitle.getText(),txtName.getText(),txtDob.getText(),Double.parseDouble(txtSalary.getText()),txtAddress.getText(),txtAddress.getText(),txtProvince.getText(),txtPostalCode.getText());
            String saveCust = customerControler.saveCustomer(customerDto);
            JOptionPane.showMessageDialog(this, saveCust);
        }catch(Exception e){
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }
    
